     not ilike '%next_lot_source%' then
    raise exception 'create_lot_for is still not calling next_lot_source';
  end if;

  if pg_get_functiondef(to_regprocedure('public.create_lot_for(uuid,date)')::oid)
     ilike '%student_tracks%' then
    raise exception 'create_lot_for still reads student_tracks; lots are meant to be decoupled';
  end if;

  raise notice 'the daily-lot engine now matches Supabase: source-driven, no track lookup';
end $$;

